    .include "macros/btlcmd.inc"

    .data

_000:
    WaitButtonABTime 15
    UpdateVar OPCODE_SET, BSCRIPT_VAR_BATTLER_SPEED_TEMP, 0
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_LAST_BATTLER_ID, BSCRIPT_VAR_BATTLER_ATTACKER
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_BATTLER_ATTACKER, BSCRIPT_VAR_MSG_BATTLER_TEMP

_013:
    GetMonBySpeedOrder BSCRIPT_VAR_BATTLER_STAT_CHANGE
    IfSameSide BATTLER_CATEGORY_ATTACKER, BATTLER_CATEGORY_SIDE_EFFECT_MON, _038
    CheckSubstitute BATTLER_CATEGORY_SIDE_EFFECT_MON, _038
    CompareMonDataToValue OPCODE_EQU, BATTLER_CATEGORY_SIDE_EFFECT_MON, BMON_DATA_HP, 0, _038
    CheckAbility CHECK_OPCODE_HAVE, BATTLER_CATEGORY_SIDE_EFFECT_MON, ABILITY_GUARD_DOG, _GUARD_DOG
    UpdateVar OPCODE_SET, BSCRIPT_VAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_ATTACK_DOWN_1_STAGE

_CHANGE:
    UpdateVar OPCODE_SET, BSCRIPT_VAR_SIDE_EFFECT_TYPE, SIDE_EFFECT_TYPE_ABILITY
    // The Attack as it was, for Rattled below.
    UpdateMonDataFromVar OPCODE_GET, BATTLER_CATEGORY_SIDE_EFFECT_MON, BMON_DATA_STAT_CHANGE_ATK, BSCRIPT_VAR_CALC_TEMP
    CheckItemHoldEffect CHECK_OPCODE_HAVE, BATTLER_CATEGORY_SIDE_EFFECT_MON, HOLD_EFFECT_INTIMIDATE_BOOST_SPEED, _ADRENALINE_ORB
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE
    GoTo _RATTLED

_ADRENALINE_ORB:
    Call BATTLE_SUBSCRIPT_ADRENALINE_ORB

// Rattled answers an Intimidate that moved the Attack with a stage of Speed,
// from the eighth generation (Pokemon Central, Prepotenza and Paura); one a
// Clear Amulet or an ability kept off does not set it off. The reference
// reads Rattled only when it is hit.
_RATTLED:
    CheckAbility CHECK_OPCODE_NOT_HAVE, BATTLER_CATEGORY_SIDE_EFFECT_MON, ABILITY_RATTLED, _038
    CompareMonDataToVar OPCODE_EQU, BATTLER_CATEGORY_SIDE_EFFECT_MON, BMON_DATA_STAT_CHANGE_ATK, BSCRIPT_VAR_CALC_TEMP, _038
    UpdateVar OPCODE_FLAG_OFF, BSCRIPT_VAR_BATTLE_STATUS_2, BATTLE_STATUS2_UPDATE_STAT_STAGES
    UpdateVar OPCODE_FLAG_OFF, BSCRIPT_VAR_BATTLE_STATUS_2, BATTLE_STATUS2_STAT_STAGE_CHANGE_SHOWN
    UpdateVar OPCODE_SET, BSCRIPT_VAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_SPEED_UP_1_STAGE
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE

_038:
    UpdateVar OPCODE_ADD, BSCRIPT_VAR_BATTLER_SPEED_TEMP, 1
    GoToIfValidMon BSCRIPT_VAR_BATTLER_SPEED_TEMP, _013
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_BATTLER_ATTACKER, BSCRIPT_VAR_LAST_BATTLER_ID
    End

// Guard Dog turns the Intimidate round and raises its Attack a stage, a Clear
// Amulet or no, but not where the Intimidate would have been stopped anyway:
// behind a substitute, as above, in Mist, or with its Attack already as low
// as it goes (Pokemon Central, Cane da Guardia). The reference declares the
// ability and nothing reads it.
_GUARD_DOG:
    CompareVarToValue OPCODE_FLAG_SET, BSCRIPT_VAR_SIDE_CONDITION_STAT_CHANGE, SIDE_CONDITION_MIST, _038
    CompareMonDataToValue OPCODE_EQU, BATTLER_CATEGORY_SIDE_EFFECT_MON, BMON_DATA_STAT_CHANGE_ATK, 0, _038
    UpdateVar OPCODE_SET, BSCRIPT_VAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_ATTACK_UP_1_STAGE
    GoTo _CHANGE
