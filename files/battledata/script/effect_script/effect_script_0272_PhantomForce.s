// Shadow Force and Phantom Force: the engine's script (d0380a487), the hit
// that breaks through protection; the first turn is the controller's
// (TryChargeTurn).
_000:
    UpdateMonData OPCODE_FLAG_ON, BATTLER_CATEGORY_ATTACKER, BMON_DATA_MOVE_EFFECT, MOVE_EFFECT_FLAG_PHANTOM_FORCE
    UpdateMonData OPCODE_FLAG_ON, BATTLER_CATEGORY_ATTACKER, BMON_DATA_MOVE_EFFECT_TEMP, MOVE_EFFECT_FLAG_PHANTOM_FORCE
    ToggleVanish BATTLER_CATEGORY_ATTACKER, TRUE
    CompareVarToValue OPCODE_EQU, BSCRIPT_VAR_BATTLER_TARGET, BATTLER_NONE, _PHANTOM_FORCE_AFTER_HIT

_PHANTOM_FORCE_HIT:
    UpdateVar OPCODE_SET, BSCRIPT_VAR_SIDE_EFFECT_FLAGS_INDIRECT, MOVE_SIDE_EFFECT_ON_HIT|MOVE_SUBSCRIPT_PTR_FEINT
    CalcCrit
    CalcDamage

_PHANTOM_FORCE_AFTER_HIT:
    UpdateMonData OPCODE_FLAG_OFF, BATTLER_CATEGORY_ATTACKER, BMON_DATA_MOVE_EFFECT, MOVE_EFFECT_FLAG_SEMI_INVULNERABLE
    Call BATTLE_SUBSCRIPT_CHARGE_MOVE_CLEANUP
    End
