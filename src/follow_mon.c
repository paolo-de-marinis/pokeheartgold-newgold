void FieldSystem_UnkSub108_Set(FieldSystemUnkSub108 *a0, Pokemon *mon, u16 species, u32 personality) {
    s8 mood;
    if (species != SPECIES_NONE && (a0->isRegistered == FALSE || a0->species != species || a0->personality != personality)) {
        a0->species = species;
        a0->personality = personality;
        mood = 0;
        a0->isRegistered = TRUE;
        a0->mon = mon;
        SetMonData(mon, MON_DATA_MOOD, &mood);
    }
}

void FieldSystem_UnkSub108_MoveMoodTowardsNeutral(FieldSystemUnkSub108 *a0) {
    s8 mood;
    if (a0->mon == NULL) {
        GF_ASSERT(FALSE);
        return;
    }

    mood = GetMonData(a0->mon, MON_DATA_MOOD, NULL);
    if (mood < 0) {
        mood++;
    } else if (mood > 0) {
        mood--;
    }
    SetMonData(a0->mon, MON_DATA_MOOD, &mood);
}

