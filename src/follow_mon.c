int SpeciesToOverworldModelIndexOffset(int species) {
    // One entry a species. Retail's stopped at Arceus; the species New Gold
    // adds have the models tools/newgold/import/import_followers.py brings
    // from hg-engine, or their base species' where hg-engine draws none, and
    // the egg and the alternate forms between the two keep model 0.
    if (species < 0 || species >= (int)NELEMS(sModelIndexLUT)) {
        return FOLLOWER_MON_NONE;
    }
    return sModelIndexLUT[species];
}

int OverworldModelLookupFormCount(int species) {
    // One entry a species, and the table is retail's: a species past its end
    // has no forms among the follower models -- New Gold's forms are species
    // with models of their own -- and reading past it gave a form count out
    // of whatever follows the table, so it answers none.
    if (species <= 0 || species > (int)NELEMS(sFormMaxLUT)) {
        return 0;
    }
    return sFormMaxLUT[species - 1];
}

BOOL OverworldModelLookupHasFemaleForm(int species) {
    if (species <= 0 || species > (int)NELEMS(sFemaleFlagLUT)) {
        return FALSE;
    }
    return sFemaleFlagLUT[species - 1];
}
